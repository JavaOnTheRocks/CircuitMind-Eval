def build_metric_comparison(openai, nvidia):
    openai_values = extract_model_values(openai)
    nvidia_values = extract_model_values(nvidia)

    percentage_metrics = [
        "global_accuracy",
        "evaluated_only_accuracy",
        "numerical_accuracy",
        "answer_completeness",
        "response_coverage",
        "valid_json_rate",
        "ai_evaluation_coverage",
    ]

    score_metrics = [
        "average_question_score",
        "end_to_end_average_score",
    ]

    comparison = {}

    for metric in percentage_metrics:
        comparison[metric] = make_metric_comparison(
            openai_values[metric],
            nvidia_values[metric],
            unit="percentage points",
        )

    for metric in score_metrics:
        comparison[metric] = make_metric_comparison(
            openai_values[metric],
            nvidia_values[metric],
            unit="score points out of 5",
        )

    # AI judge dimensions
    for dimension in SEMANTIC_DIMENSIONS:
        comparison[dimension] = make_metric_comparison(
            openai_values["semantic_metrics"][dimension],
            nvidia_values["semantic_metrics"][dimension],
            unit="percentage points or source metric units",
        )

    return comparison


