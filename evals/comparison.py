def compare_questions(openai, nvidia):
    openai_questions = openai.get(
        "per_question_results",
        {}
    )

    nvidia_questions = nvidia.get(
        "per_question_results",
        {}
    )

    if not isinstance(openai_questions, dict):
        openai_questions = {}

    if not isinstance(nvidia_questions, dict):
        nvidia_questions = {}

    task_ids = sorted(
        set(openai_questions) | set(nvidia_questions)
    )

    output = {}

    for task_id in task_ids:
        openai_result = openai_questions.get(task_id, {})
        nvidia_result = nvidia_questions.get(task_id, {})

        if not isinstance(openai_result, dict):
            openai_result = {}

        if not isinstance(nvidia_result, dict):
            nvidia_result = {}

        openai_score = first_available(
            openai_result,
            [
                ("final_question_score",),
                ("question_score",),
            ]
        )

        nvidia_score = first_available(
            nvidia_result,
            [
                ("final_question_score",),
                ("question_score",),
            ]
        )

        openai_score = to_number(openai_score)
        nvidia_score = to_number(nvidia_score)

        if openai_score is None or nvidia_score is None:
            question_winner = "incomplete_comparison"

        elif openai_score > nvidia_score:
            question_winner = "OpenAI"

        elif nvidia_score > openai_score:
            question_winner = "NVIDIA"

        else:
            question_winner = "Tie"

        output[task_id] = {
            "openai": {
                "score": openai_score,
                "raw_judge_score": openai_result.get(
                    "raw_judge_score"
                ),
                "valid_json": openai_result.get(
                    "response_valid_json"
                ),
                "evaluation_status": openai_result.get(
                    "ai_evaluation_status"
                ),
                "numeric_all_correct": openai_result.get(
                    "numeric_all_correct"
                ),
                "all_required_fields_present": openai_result.get(
                    "all_required_fields_present"
                ),
            },

            "nvidia": {
                "score": nvidia_score,
                "raw_judge_score": nvidia_result.get(
                    "raw_judge_score"
                ),
                "valid_json": nvidia_result.get(
                    "response_valid_json"
                ),
                "evaluation_status": nvidia_result.get(
                    "ai_evaluation_status"
                ),
                "numeric_all_correct": nvidia_result.get(
                    "numeric_all_correct"
                ),
                "all_required_fields_present": nvidia_result.get(
                    "all_required_fields_present"
                ),
            },

            "winner": question_winner,
        }

    return output


def count_question_wins(per_question):
    counts = {
        "openai_wins": 0,
        "nvidia_wins": 0,
        "ties": 0,
        "incomplete": 0,
        "compared_questions": 0,
    }

    for result in per_question.values():
        winner = result.get("winner")

        if winner == "OpenAI":
            counts["openai_wins"] += 1
            counts["compared_questions"] += 1

        elif winner == "NVIDIA":
            counts["nvidia_wins"] += 1
            counts["compared_questions"] += 1

        elif winner == "Tie":
            counts["ties"] += 1
            counts["compared_questions"] += 1

        else:
            counts["incomplete"] += 1

    return counts


