def validate_benchmark(openai, nvidia):
    openai_values = extract_model_values(openai)
    nvidia_values = extract_model_values(nvidia)

    openai_size = openai_values["dataset_size"]
    nvidia_size = nvidia_values["dataset_size"]

    same_dataset_size = (
        isinstance(openai_size, int)
        and isinstance(nvidia_size, int)
        and openai_size > 0
        and openai_size == nvidia_size
    )

    openai_response = openai_values["response_coverage"]
    nvidia_response = nvidia_values["response_coverage"]

    openai_evaluation = openai_values[
        "ai_evaluation_coverage"
    ]
    nvidia_evaluation = nvidia_values[
        "ai_evaluation_coverage"
    ]

    complete_response_coverage = (
        openai_response == 100
        and nvidia_response == 100
    )

    complete_ai_evaluation = (
        openai_evaluation == 100
        and nvidia_evaluation == 100
    )

    # Check metric-calculator completion flags as an additional
    # validation signal when those flags are available.
    openai_status = openai_values["benchmark_status"]
    nvidia_status = nvidia_values["benchmark_status"]

    status_flags = []

    for status in (openai_status, nvidia_status):
        if isinstance(status, dict):
            flag = status.get("is_complete")

            if isinstance(flag, bool):
                status_flags.append(flag)

    status_complete = (
        all(status_flags)
        if status_flags
        else None
    )

    ready = (
        same_dataset_size
        and complete_response_coverage
        and complete_ai_evaluation
        and status_complete is not False
    )

    return {
        "same_dataset_size": same_dataset_size,
        "openai_dataset_size": openai_size,
        "nvidia_dataset_size": nvidia_size,

        "openai_response_coverage_percent": openai_response,
        "nvidia_response_coverage_percent": nvidia_response,

        "openai_ai_evaluation_coverage_percent": openai_evaluation,
        "nvidia_ai_evaluation_coverage_percent": nvidia_evaluation,

        "complete_response_coverage": complete_response_coverage,
        "complete_ai_evaluation_coverage": complete_ai_evaluation,

        "openai_metric_calculator_complete": (
            openai_status.get("is_complete")
            if isinstance(openai_status, dict)
            else None
        ),

        "nvidia_metric_calculator_complete": (
            nvidia_status.get("is_complete")
            if isinstance(nvidia_status, dict)
            else None
        ),

        "ready_for_final_comparison": ready,
    }


