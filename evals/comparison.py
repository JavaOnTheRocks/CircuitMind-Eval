def determine_winner(comparison, validation):
    if not validation["ready_for_final_comparison"]:
        return {
            "winner": None,
            "status": "INCOMPLETE",
            "primary_metric": "global_accuracy",
            "reason": (
                "A final winner requires matching dataset sizes, "
                "100% response coverage, and 100% AI evaluation "
                "coverage for both models."
            ),
        }

    primary = comparison["global_accuracy"]

    openai_score = primary["openai"]
    nvidia_score = primary["nvidia"]

    if openai_score is None or nvidia_score is None:
        return {
            "winner": None,
            "status": "PENDING",
            "primary_metric": "global_accuracy",
            "reason": "Global accuracy is unavailable.",
        }

    if openai_score > nvidia_score:
        winner = "OpenAI"
        reason = "OpenAI achieved higher global accuracy."

    elif nvidia_score > openai_score:
        winner = "NVIDIA"
        reason = "NVIDIA achieved higher global accuracy."

    else:
        # Secondary tie-breaker: average AI-judge score.
        openai_average = comparison[
            "average_question_score"
        ]["openai"]

        nvidia_average = comparison[
            "average_question_score"
        ]["nvidia"]

        if openai_average is None or nvidia_average is None:
            winner = "Tie"
            reason = (
                "Global accuracy is tied and average question "
                "scores are unavailable."
            )

        elif openai_average > nvidia_average:
            winner = "OpenAI"
            reason = (
                "Global accuracy is tied; OpenAI has the higher "
                "average question score."
            )

        elif nvidia_average > openai_average:
            winner = "NVIDIA"
            reason = (
                "Global accuracy is tied; NVIDIA has the higher "
                "average question score."
            )

        else:
            winner = "Tie"
            reason = (
                "Both models have equal global accuracy and "
                "average question scores."
            )

    return {
        "winner": winner,
        "status": "COMPLETED",
        "primary_metric": "global_accuracy",
        "secondary_metric": "average_question_score",
        "reason": reason,
    }


