def get_nested(data, *keys):
    value = data

    for key in keys:
        if not isinstance(value, dict):
            return None

        value = value.get(key)

    return value


def first_available(data, paths, default=None):
    """
    Return the first non-None value found in a list of paths.

    Each path is a tuple of dictionary keys.
    """

    for path in paths:
        value = get_nested(data, *path)

        if value is not None:
            return value

    return default


def to_number(value):
    if isinstance(value, bool):
        return None

    if isinstance(value, (int, float)):
        return float(value)

    return None


def safe_difference(openai_value, nvidia_value):
    openai_value = to_number(openai_value)
    nvidia_value = to_number(nvidia_value)

    if openai_value is None or nvidia_value is None:
        return None

    return round(nvidia_value - openai_value, 4)


def determine_metric_leader(openai_value, nvidia_value):
    openai_value = to_number(openai_value)
    nvidia_value = to_number(nvidia_value)

    if openai_value is None or nvidia_value is None:
        return "Not available"

    if openai_value > nvidia_value:
        return "OpenAI"

    if nvidia_value > openai_value:
        return "NVIDIA"

    return "Tie"


def make_metric_comparison(
    openai_value,
    nvidia_value,
    unit="percentage points"
):
    difference = safe_difference(
        openai_value,
        nvidia_value
    )

    return {
        "openai": to_number(openai_value),
        "nvidia": to_number(nvidia_value),
        "difference_nvidia_minus_openai": difference,
        "difference_unit": unit,
        "better_performance": determine_metric_leader(
            openai_value,
            nvidia_value
        ),
    }


def format_number(value, decimals=2):
    value = to_number(value)

    if value is None:
        return "N/A"

    return f"{value:.{decimals}f}"


def format_percentage(value):
    value = to_number(value)

    if value is None:
        return "N/A"

    return f"{value:.2f}%"


