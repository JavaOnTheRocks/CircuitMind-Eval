# ============================================================

def generate_comparison_report():
    print("\n")
    print("=" * 110)
    print("CIRCUITMIND-EVAL: MODEL COMPARISON")
    print("=" * 110)

    combined_file = METRICS_DIR / "benchmark_metrics.json"

    benchmark = load_json(combined_file)

    models = benchmark.get("models", {})

    openai = models.get("openai")
    nvidia = models.get("nvidia")

    if not isinstance(openai, dict):
        raise ValueError(
            "OpenAI metrics are missing from benchmark_metrics.json."
        )

    if not isinstance(nvidia, dict):
        raise ValueError(
            "NVIDIA metrics are missing from benchmark_metrics.json."
        )

    # Extract model values
    openai_values = extract_model_values(openai)
    nvidia_values = extract_model_values(nvidia)

    # Main comparison
    comparison = build_metric_comparison(
        openai,
        nvidia
    )

    # Validation
    validation = validate_benchmark(
        openai,
        nvidia
    )

    # Winner
    final_result = determine_winner(
        comparison,
        validation
    )

    # Per-question results
    per_question = compare_questions(
        openai,
        nvidia
    )

    win_counts = count_question_wins(per_question)

    # Score distribution
    score_distribution = compare_score_distributions(
        openai,
        nvidia
    )

    report = {
        "benchmark": "CircuitMind-Eval",

        "generated_at": datetime.now(
            timezone.utc
        ).isoformat(),

        "dataset_size": benchmark.get(
            "dataset_size"
        ),

        "coverage_validation": validation,

        "metric_comparison": comparison,

        "score_distribution_comparison": score_distribution,

        "per_question_comparison": per_question,

        "per_question_win_counts": win_counts,

        "final_result": final_result,

        "methodology": {
            "primary_metric": "global_accuracy",
            "secondary_metric": "average_question_score",
            "deterministic_metrics": [
                "numerical_accuracy",
                "answer_completeness",
            ],
            "ai_judge_dimensions": list(
                SEMANTIC_DIMENSIONS
            ),
            "winner_requires_complete_coverage": True,
            "judge_receives_original_circuit_image": False,
        },
    }

    # Save output files
    json_path = OUTPUT_DIR / "model_comparison.json"
    markdown_path = OUTPUT_DIR / "model_comparison.md"

    save_json(json_path, report)

    markdown_report = generate_markdown_report(
        report
    )

    save_text(
        markdown_path,
        markdown_report
    )

    # Print terminal report
    print_metric_table(comparison)

    print_coverage(validation)

    print_question_results(
        per_question,
        win_counts
    )

    print_final_result(final_result)

    print_section("GENERATED REPORT FILES")

    print(f"JSON report:     {json_path}")
    print(f"Markdown report: {markdown_path}")

    print("\nComparison report generated successfully.")

    return report


# ============================================================
# COMMAND LINE ENTRY POINT
# ============================================================

def main():
    parser = argparse.ArgumentParser(
        description=(
            "Compare OpenAI and NVIDIA results "
            "for the CircuitMind-Eval benchmark."
        )
    )

    parser.add_argument(
        "--model",
        choices=["both"],
        default="both",
        help="Comparison requires both models.",
    )

    parser.parse_args()

    generate_comparison_report()


if __name__ == "__main__":
    main()